export const CINEMATIC_MOVEMENTS_COUNT = CINEMATIC_CAMERA_MOVEMENTS.length;

export function getCinematicMovement(query: string): CinematicMovementEntry | undefined {
  if (!query) return undefined;
  const q = query.trim().toLowerCase();
  return CINEMATIC_CAMERA_MOVEMENTS.find(
    (m) =>
      m.id.toLowerCase() === q ||
      m.label.toLowerCase() === q ||
      m.aliases.some((a) => a.toLowerCase() === q),
  );
}
